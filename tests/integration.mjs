import assert from 'node:assert/strict';
const base = 'http://127.0.0.1:4173';
const send = body => fetch(base + '/api/rsvp', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: base }, body: JSON.stringify(body) });
const data = { name: 'Prueba local', attendance: 'yes', guests: 2, message: 'Verificación', dietary: '' };
const create = await send(data);
assert.equal(create.status, 201);
const receipt = await create.json();
const update = await send({ ...data, ...receipt, attendance: 'no' });
assert.equal(update.status, 200);
const bad = await send({ ...data, ...receipt, editToken: crypto.randomUUID() });
assert.equal(bad.status, 403);
const privateRows = await fetch(base + '/api/confirmations');
assert.equal(privateRows.status, 403);
const list = await fetch(base + '/api/confirmations', { headers: { 'oai-authenticated-user-email': 'albertoafm96@gmail.com' } });
assert.equal(list.status, 200);
const rows = (await list.json()).confirmations;
const row = rows.find(row => row.id === receipt.id);
assert.equal(row.guests, 0);
assert.equal(row.attendance, 'no');
assert.equal('edit_token' in row, false);
console.log('D1 integration: create, update, authorization and persistence passed');
